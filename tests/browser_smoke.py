"""Browser integration checks. Run against a local HTTP server; uses installed Chrome."""
import pathlib, sys, tempfile, json, argparse
try:
    from playwright.sync_api import sync_playwright, expect
except ImportError:
    sys.path.insert(0, str(pathlib.Path(tempfile.gettempdir()) / 'hci-browser-tools'))
    from playwright.sync_api import sync_playwright, expect

parser=argparse.ArgumentParser()
parser.add_argument('--url',default='http://127.0.0.1:4173')
args=parser.parse_args()
out=pathlib.Path(tempfile.gettempdir())/'clarity-browser-artifacts'
out.mkdir(exist_ok=True)
errors=[]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=r'C:\Program Files\Google\Chrome\Application\chrome.exe',headless=True)
    context=browser.new_context(viewport={'width':1440,'height':1000},accept_downloads=True)
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(args.url)
    expect(page.get_by_role('heading',name='What’s on your mind?')).to_be_visible()
    page.screenshot(path=str(out/'chat-desktop.png'),full_page=True)
    page.get_by_role('button',name='Debug an error').click()
    expect(page.locator('.flag')).to_have_count(1)
    original=page.locator('#composer').inner_text()
    page.locator('.flag').click()
    expect(page.get_by_role('heading',name='Review before sharing')).to_be_visible()
    page.screenshot(path=str(out/'review-desktop.png'),full_page=True)
    page.get_by_role('button',name='Mask information',exact=True).click()
    assert 'sk-test-' not in page.locator('#composer').inner_text()
    page.get_by_role('button',name='Undo masking',exact=True).click()
    assert page.locator('#composer').inner_text()==original
    page.get_by_role('link',name='Privacy dashboard',exact=True).last.click()
    page.get_by_role('link',name='Back to chat').click()
    assert page.locator('#composer').inner_text()==original
    page.locator('.flag').click()
    page.get_by_role('button',name='Mask information',exact=True).click()
    page.get_by_role('button',name='Send',exact=True).click()
    expect(page.locator('.message.user')).to_have_count(1)
    assert 'sk-test-' not in page.locator('.message.user').inner_text()
    page.locator('#composer').fill('Could you show an example?')
    page.locator('#composer').press('Control+Enter')
    expect(page.locator('.message.assistant')).to_have_count(2)
    assert 'Authorization header' in page.locator('.message.assistant').last.inner_text()
    page.reload()
    expect(page.locator('.message.user')).to_have_count(2)
    print('PASS masking, undo, navigation preservation, send, follow-up, reload')

    page.evaluate('localStorage.clear()');page.goto(args.url)
    page.get_by_role('button',name='Draft a message').click()
    expect(page.locator('.flag')).to_have_count(3)
    page.get_by_role('button',name='3 details to review').click()
    page.get_by_role('button',name='Review multiple changes').click()
    expect(page.locator('input[name=batch]')).to_have_count(3)
    page.get_by_role('button',name='Apply selected changes').click()
    expect(page.locator('.flag')).to_have_count(0)
    page.get_by_role('button',name='Undo masking',exact=True).click()
    expect(page.locator('.flag')).to_have_count(3)
    print('PASS multiple flags and batch undo')

    page.evaluate('localStorage.clear()');page.goto(args.url)
    page.get_by_role('button',name='Find a place nearby').click()
    page.locator('.flag').focus();page.locator('.flag').press('Enter')
    page.get_by_role('button',name='Keep unchanged',exact=True).click()
    expect(page.locator('.flag.kept')).to_have_count(1)
    page.get_by_role('button',name='Send',exact=True).click()
    assert 'Punggol' in page.locator('.message.user').inner_text()
    page.get_by_role('link',name='Privacy dashboard',exact=True).last.click()
    page.screenshot(path=str(out/'dashboard-desktop.png'),full_page=True)
    page.get_by_role('button',name='Delete Neighbourhood',exact=True).click()
    expect(page.get_by_text('The original conversation and its text remain unchanged.')).to_be_visible()
    page.get_by_role('button',name='Cancel',exact=True).click()
    page.get_by_role('button',name='Delete Neighbourhood',exact=True).click()
    page.get_by_role('button',name='Delete',exact=True).click()
    page.get_by_role('button',name='Removed 1',exact=True).click()
    page.get_by_role('button',name='Restore',exact=True).click()
    page.get_by_role('button',name='All information 4',exact=True).click()
    expect(page.get_by_role('button',name='Delete Neighbourhood',exact=True)).to_be_visible()
    print('PASS keyboard review, deliberate retention, scoped delete, restore')

    page.get_by_role('link',name='Privacy preferences',exact=True).last.click()
    page.locator('[name=warningMode][value=pause]').check()
    page.get_by_role('button',name='Save preferences',exact=True).click()
    page.get_by_role('link',name='Back to chat').click()
    page.locator('#composer').fill('Email alex@example.test about the error.')
    page.get_by_role('button',name='Send',exact=True).click()
    expect(page.get_by_role('heading',name='Review before sending?')).to_be_visible()
    page.get_by_role('button',name='Send unchanged',exact=True).click()
    expect(page.locator('.message.user')).to_have_count(2)
    page.goto(args.url+'/#preferences')
    page.get_by_role('button',name='Try the reuse example').click()
    page.locator('#demo-item').select_option('memory-location')
    page.get_by_role('button',name='Run example').click()
    expect(page.get_by_role('heading',name='Allow this detail for this example?')).to_be_visible()
    page.get_by_role('button',name='Do not use',exact=True).click()
    expect(page.get_by_text('Not used in this example',exact=True)).to_be_visible()
    page.get_by_role('button',name='Close',exact=True).click()
    print('PASS pause preference, explicit override, reuse permission')

    research=context.new_page();research.on('pageerror',lambda e:errors.append(str(e)))
    research.goto(args.url+'/researcher.html')
    expect(research.get_by_role('button',name='Prepare task',exact=True)).to_be_disabled()
    research.locator('#consent').check()
    research.locator('#study-mode').select_option('timed')
    research.get_by_role('button',name='Save session setup').click()
    research.get_by_role('button',name='Prepare task',exact=True).click()
    research.locator('#modal').get_by_role('button',name='Prepare task',exact=True).click()
    expect(page.get_by_role('button',name='Begin task')).to_be_visible()
    page.get_by_role('button',name='Begin task').click()
    page.get_by_role('button',name='1 detail to review').click()
    page.get_by_role('button',name='Mask information',exact=True).click()
    page.get_by_role('button',name='Send',exact=True).click()
    expect(research.locator('[data-field=outcome]')).to_have_count(1)
    research.locator('[data-field=outcome]').select_option('success')
    research.locator('[data-field=assistance]').select_option('none')
    with research.expect_download() as d:
        research.get_by_role('button',name='Export JSON').click()
    export=d.value;export.save_as(str(out/'sample-export.json'))
    data=json.loads((out/'sample-export.json').read_text())
    assert len(data['trials'])==1 and data['trials'][0]['observedSuccess'] is True
    assert data['trials'][0]['durationMs']>0
    assert data['trials'][0]['mode']=='timed'
    raw=json.dumps(data)
    assert not any(s in raw for s in ['sk-test-','FICTIONAL7ALPHA','Punggol','maya@example.test'])
    research.locator('#condition').select_option('notice')
    research.locator('#scenario').select_option('maskB')
    research.get_by_role('button',name='Prepare task',exact=True).click()
    research.locator('#modal').get_by_role('button',name='Prepare task',exact=True).click()
    expect(page.get_by_role('button',name='Begin task')).to_be_visible()
    page.get_by_role('button',name='Begin task').click()
    expect(page.locator('.flag')).to_have_count(0)
    page.get_by_role('button',name='1 detail to review').click()
    page.get_by_role('button',name='Mask information',exact=True).click()
    page.get_by_role('button',name='Send',exact=True).click()
    expect(research.locator('[data-field=outcome]')).to_have_count(2)
    research.screenshot(path=str(out/'researcher-desktop.png'),full_page=True)
    print('PASS consent gating, cross-tab setup, timer, both conditions, anonymous export')

    mobile=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    m=mobile.new_page();m.on('pageerror',lambda e:errors.append(str(e)))
    m.goto(args.url)
    m.screenshot(path=str(out/'chat-mobile.png'),full_page=True)
    m.get_by_role('button',name='Debug an error').click()
    m.get_by_role('button',name='1 detail to review').click()
    m.screenshot(path=str(out/'review-mobile.png'),full_page=True)
    assert m.evaluate('document.documentElement.scrollWidth <= innerWidth')
    m.get_by_role('button',name='Mask information',exact=True).click()
    m.get_by_role('button',name='Send',exact=True).click()
    expect(m.locator('.message.user')).to_have_count(1)
    m.get_by_role('button',name='Open navigation menu').click()
    m.get_by_role('link',name='Privacy preferences',exact=True).click()
    expect(m.get_by_role('heading',name='Privacy preferences',exact=True)).to_be_visible()
    print('PASS mobile layout, review/send and navigation')
    assert not errors, errors
    print('PASS zero browser page errors')
    browser.close()
